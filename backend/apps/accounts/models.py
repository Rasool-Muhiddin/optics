import hashlib
import secrets

from django.conf import settings
from django.contrib.auth.models import AbstractUser
from django.core.exceptions import ValidationError
from django.db import models

from apps.core.models import LabScopedModel


def hash_secret(value):
    """Tokens and device keys are stored only as SHA-256 digests."""
    return hashlib.sha256(value.encode()).hexdigest()


def new_secret():
    return secrets.token_hex(20)


class User(AbstractUser):
    """
    Custom user model, defined from day one so it can grow without a painful swap.

    Lab membership is `labs.LabUser` (`user.lab_membership`); doctor profiles
    (`doctors.DoctorProfile`) attach in P7.
    """

    class Meta:
        verbose_name = "user"
        verbose_name_plural = "users"


class Device(LabScopedModel):
    """A desktop installation activated for a lab (counts against the plan's `max_devices`)."""

    device_id = models.CharField(max_length=64, help_text="Stable id generated by the desktop app.")
    name = models.CharField(max_length=100, blank=True)
    key_digest = models.CharField(max_length=64, unique=True, editable=False)
    is_active = models.BooleanField(default=True)
    app_version = models.CharField(max_length=30, blank=True)
    last_login_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["id"]
        constraints = [
            models.UniqueConstraint(fields=["lab", "device_id"], name="unique_device_per_lab"),
        ]

    def __str__(self):
        return f"{self.name or self.device_id} ({self.lab})"

    def rotate_key(self):
        """Sets a new device key and returns it (plain text is never stored)."""
        key = new_secret()
        self.key_digest = hash_secret(key)
        return key

    def clean(self):
        super().clean()
        if self.is_active and self.lab_id:
            from apps.billing.features import check_device_limit

            check_device_limit(self.lab, exclude_pk=self.pk, error_class=ValidationError)


class AuthToken(models.Model):
    """
    API token, one per login (per device), so logging out or deactivating a device only
    revokes that device. Sent as `Authorization: Token <key>`; only the digest is stored.
    """

    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="auth_tokens")
    device = models.ForeignKey(
        Device, on_delete=models.CASCADE, null=True, blank=True, related_name="auth_tokens"
    )
    digest = models.CharField(max_length=64, unique=True, editable=False)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Token for {self.user} ({self.device or 'no device'})"

    @classmethod
    def issue(cls, user, device=None):
        """Creates a token and returns `(token, plain_key)`."""
        key = new_secret()
        return cls.objects.create(user=user, device=device, digest=hash_secret(key)), key
